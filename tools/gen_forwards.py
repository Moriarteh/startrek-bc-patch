#!/usr/bin/env python3
"""Generate /EXPORT forwarder pragmas from a real DLL's export table.

Reads the *original* binkw32.dll, enumerates every export (ordinal + name),
and emits one `#pragma comment(linker, "/EXPORT:...")` per export that forwards
to the renamed original (binkw32_orig.dll).

Why pragmas and not a .def file? stdcall exports are decorated like
`_BinkOpen@8`. In a .def the parser can mistake the `@8` for an ordinal spec.
The /EXPORT form uses a comma before the ordinal, so the name stays intact:

    /EXPORT:_BinkOpen@8=binkw32_orig._BinkOpen@8,@35

Usage:
    python gen_forwards.py <path-to-original-binkw32.dll> <output-header>
"""
import struct
import sys


def parse_exports(path):
    f = open(path, "rb").read()
    pe = struct.unpack_from("<I", f, 0x3C)[0]
    nsec = struct.unpack_from("<H", f, pe + 6)[0]
    optsz = struct.unpack_from("<H", f, pe + 20)[0]
    opt = pe + 24
    magic = struct.unpack_from("<H", f, opt)[0]
    dd = opt + (96 if magic == 0x10B else 112)
    exp_rva, _ = struct.unpack_from("<II", f, dd)  # export dir = data dir 0

    sh = opt + optsz
    secs = []
    for i in range(nsec):
        o = sh + i * 40
        vsz, va, rsz, ra = struct.unpack_from("<IIII", f, o + 8)
        secs.append((va, vsz, ra, rsz))

    def r2o(rva):
        for va, vsz, ra, rsz in secs:
            if va <= rva < va + max(vsz, rsz):
                return ra + (rva - va)
        raise ValueError("rva %x not in any section" % rva)

    o = r2o(exp_rva)
    (_cf, _ts, _maj, _mn, _name, base, naddr, nname,
     a_addr, a_name, a_ord) = struct.unpack_from("<IIHHIIIIIII", f, o)

    names = {}
    ao, oo = r2o(a_name), r2o(a_ord)
    for i in range(nname):
        nrva = struct.unpack_from("<I", f, ao + i * 4)[0]
        ordi = struct.unpack_from("<H", f, oo + i * 2)[0]
        s = r2o(nrva)
        names[ordi] = f[s:f.index(b"\0", s)].decode("latin1")

    funcs = r2o(a_addr)
    out = []  # (ordinal, name_or_None)
    for i in range(naddr):
        fr = struct.unpack_from("<I", f, funcs + i * 4)[0]
        if fr == 0:
            continue
        out.append((base + i, names.get(i)))
    return out


def main():
    if len(sys.argv) != 3:
        print(__doc__)
        sys.exit(1)
    src, dst = sys.argv[1], sys.argv[2]
    exports = parse_exports(src)
    target = "binkw32_orig"
    lines = [
        "// Auto-generated by tools/gen_forwards.py. Do not edit by hand.",
        "// Forwards every export of the original binkw32.dll to binkw32_orig.dll.",
        "#pragma once",
        "",
    ]
    for ordi, name in exports:
        if name:
            lines.append(
                '#pragma comment(linker, "/EXPORT:%s=%s.%s,@%d")'
                % (name, target, name, ordi)
            )
        else:
            # Nameless export: forward by ordinal only.
            lines.append(
                '#pragma comment(linker, "/EXPORT:#%d=%s.#%d,@%d,NONAME")'
                % (ordi, target, ordi, ordi)
            )
    open(dst, "w", newline="\n").write("\n".join(lines) + "\n")
    print("Wrote %d forwarders to %s" % (len(exports), dst))


if __name__ == "__main__":
    main()
